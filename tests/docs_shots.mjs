await page.waitForTimeout(300);
await snap('pist-mesafesi');
await page.locator('[data-testid="cov-show"]').click().catch(() => {});
await page.waitForTimeout(800);
await snap('oneriler');
await page.locator('[data-testid="ghost-bar"] .ibtn').click().catch(() => {});
// ölçüm
await page.locator('[data-testid="view-measure"]').click();
await page.waitForTimeout(500);
for (let i = 0; i < 3; i++) await page.locator('[data-testid="ms-demo"]').click();
